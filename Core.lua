local addonName, addon = ...

local SCHEMA_VERSION = 4

local function DefaultDataSettings()
    return { channels = { party = true, guild = true, friends = true }, cleanupOldPlayers = true }
end

addon.name = addonName
addon.version = C_AddOns.GetAddOnMetadata(addonName, "Version") or "development"
addon.initialized = false
addon.ready = false

function addon:Print(message)
    DEFAULT_CHAT_FRAME:AddMessage("|cff66ccff[LockInTools]|r " .. message)
end

function addon:GetPlayerDisplayName(name)
    if (issecretvalue and issecretvalue(name)) or type(name) ~= "string" then return "" end
    -- Strip realms only for display; saved identities and native actions need full names.
    return name:match("^[^%-]+") or ""
end

function addon:Initialize()
    if self.initialized then
        return
    end

    local database = LockInToolsDB

    -- Preserve data from a newer release when an older addon is installed.
    if type(database) == "table"
        and type(database.schemaVersion) == "number"
        and database.schemaVersion > SCHEMA_VERSION then
        self.db = {
            schemaVersion = SCHEMA_VERSION,
            showWelcome = type(database.showWelcome) ~= "boolean" or database.showWelcome,
            data = DefaultDataSettings(),
        }
        self.savedDataReadOnly = true
    else
        if type(database) ~= "table" then
            database = {}
        end

        if type(database.showWelcome) ~= "boolean" then
            database.showWelcome = true
        end

        database.chat, database.group = nil, nil
        if type(database.data) ~= "table" then database.data = DefaultDataSettings() end
        if type(database.data.cleanupOldPlayers) ~= "boolean" then database.data.cleanupOldPlayers = true end
        if type(database.data.channels) ~= "table" then database.data.channels = {} end
        for _, channel in ipairs({ "party", "guild", "friends" }) do
            if type(database.data.channels[channel]) ~= "boolean" then database.data.channels[channel] = true end
        end
        database.data.channels.global = nil
        if type(database.roster) == "table" then database.roster.groupFingerprint = nil end

        database.schemaVersion = SCHEMA_VERSION
        LockInToolsDB = database
        self.db = database
    end

    if type(self.db.position) ~= "table" then self.db.position = {} end
    local position = self.db.position
    if type(position.showDeathMarkers) ~= "boolean" then position.showDeathMarkers = true end
    -- Older releases default missing sharing preferences to on.
    position.sharing = false
    position.groupFingerprint, position.keepLastKnown = nil, nil
    position.showPlayerIcons, position.peers = nil, nil

    self.initialized = true
    self.startupEvents:UnregisterEvent("ADDON_LOADED")
    self:InitializeData()
    self:InitializeBurned()
    self:InitializeRoster()
    self:InitializeDeathMarkers()
    self:InitializeRanking()
    self:InitializeRestedXP()
    self:InitializeRestedXPSkin()
    self:InitializePlayerDataCleanup()

    -- Also support loading after login through an addon manager.
    if IsLoggedIn() then
        self:OnLogin()
    end
end

function addon:OnLogin()
    if not self.initialized or self.ready then
        return
    end

    self.ready = true
    self.startupEvents:UnregisterEvent("PLAYER_LOGIN")
    self:InitializeMinimapButton()
    self:RefreshRestedXPSkin()

    if self.savedDataReadOnly then
        self:Print("Saved settings belong to a newer version; preferences are read-only.")
    end

    if self.db.showWelcome then
        self:Print("Loaded version " .. self.version .. ". Type /lit to open Content.")
    end

    if not self.savedDataReadOnly then
        self:CleanupLegacyChannels()
        self.legacyChannelEvents = self:RegisterGameEvents({ "PLAYER_ENTERING_WORLD", "CHAT_MSG_CHANNEL_NOTICE" },
            function(self, event, ...)
                local reason, name = ..., select(9, ...)
                if event == "PLAYER_ENTERING_WORLD" or (not (issecretvalue and issecretvalue(reason))
                    and (reason == "YOU_JOINED" or reason == "YOU_CHANGED")) then self:CleanupLegacyChannels(name) end
            end)
    end
    self:OnDataLogin()
    self:OnRosterLogin()
    self:OnFriendsLogin()
    if self.OnRankingLogin then self:OnRankingLogin() end
    self:UpdatePlayerDataCleanupTimer()
    if self.db.showWelcome and self.db.setupComplete ~= true
        and not self.savedDataReadOnly then
        self:OpenContent()
    end
end

function addon:CleanupLegacyChannels(noticedChannel)
    if not self.ready or self.savedDataReadOnly then return end
    local channels = {}
    local function collect(name)
        if (issecretvalue and issecretvalue(name)) or type(name) ~= "string" or #name ~= 31 then return end
        local normalized = name:lower()
        -- Only the complete namespaces generated by the retired group system.
        if normalized:match("^lit%x+$") or normalized:match("^litdata%x+$") then channels[normalized] = name end
    end
    -- Join notices can precede native channel-list updates.
    collect(noticedChannel)
    if type(GetChannelList) == "function" then
        local function collectJoined(...)
            for index = 2, select("#", ...), 3 do collect(select(index, ...)) end
        end
        collectJoined(GetChannelList())
    end
    local frames = {}
    local function collectFrame(frame)
        frames[#frames + 1] = frame
        for _, name in pairs(frame.channelList or {}) do collect(name) end
    end
    if ChatFrameUtil and type(ChatFrameUtil.ForEachChatFrame) == "function" then
        ChatFrameUtil.ForEachChatFrame(collectFrame)
    elseif DEFAULT_CHAT_FRAME then collectFrame(DEFAULT_CHAT_FRAME) end
    -- Snapshot before leaving: native leaves can renumber channels and alter subscriptions.
    for _, name in pairs(channels) do
        for _, frame in ipairs(frames) do
            if type(frame.RemoveChannel) == "function" then pcall(frame.RemoveChannel, frame, name) end
        end
        if type(LeaveChannelByName) == "function" then pcall(LeaveChannelByName, name) end
    end
end

function addon:SetShowWelcome(enabled)
    if not self.initialized then
        self:Print("Still loading. Please try again after login.")
        return
    end

    if self.savedDataReadOnly then
        self:Print("Update LockInTools before changing saved preferences.")
        return
    end

    self.db.showWelcome = enabled
    self:Print("Login message and initial Content view " .. (enabled and "enabled." or "disabled."))
end

addon.startupEvents = addon:RegisterGameEvents({ "ADDON_LOADED" }, function(self, _, loadedAddonName)
    if loadedAddonName == addonName then self:Initialize() end
end)
addon.startupEvents:RegisterEvent("PLAYER_LOGIN", function() addon:OnLogin() end)
